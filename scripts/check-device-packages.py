#!/usr/bin/env python3
"""DEVICE_PACKAGES check (upstream-style, WARN MODE).

Reads the targetinfo generated by defconfig and warns for every device
package of the enabled profile that is not selected in .config. A device
package silently dropped via an unmet dependency does NOT appear as a
dropped config line, so the fragment-survival guard cannot catch it;
this check closes that hole.

WARN MODE, deliberately: this parser has not yet been validated against
a real build's targetinfo file (targetinfo field names vary), so it must
never fail a good build. It exits 0 always; after one clean run confirms
the parser against real output, it can graduate to failing. A crash or a
missing file prints a note and exits 0; the workflow step additionally
guards the call, so a broken checker can never block a build.

Usage: check-device-packages.py <config> <targetinfo> <device>
  config:     .config after defconfig
  targetinfo: tmp/info/.targetinfo-<target> (e.g. qualcommax)
  device:     profile name, e.g. jdcloud_re-ss-01
"""
import re
import sys


def norm(s):
    return re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_")


def main(config_path, targetinfo_path, device):
    try:
        selected = set()
        with open(config_path) as f:
            for line in f:
                m = re.match(r"^(CONFIG_\S+)=([ym])$", line.strip())
                if m:
                    selected.add(m.group(1))
    except OSError:
        print("(no .config for device-package check; skipping)")
        return 0
    try:
        with open(targetinfo_path) as f:
            text = f.read()
    except OSError:
        print("(no targetinfo file; skipping device-package check)")
        return 0

    dev_norm = norm(device)
    warned = 0
    for block in re.split(r"\n\s*\n", text):
        name = None
        pkgs = None
        for line in block.splitlines():
            if ":" not in line:
                continue
            key, val = line.split(":", 1)
            key = key.strip()
            val = val.strip()
            if key in ("Target-Profile-Name", "Target-Profile"):
                name = val
            elif key == "Target-Profile-Packages":
                pkgs = val.split()
        if not name or not pkgs:
            continue
        n = norm(name)
        # Enabled profile = its name matches this build's device.
        if not n or (n not in dev_norm and dev_norm not in n):
            continue
        for pkg in pkgs:
            if pkg.startswith("-"):
                continue  # negative selection: package to remove
            sym = "CONFIG_PACKAGE_" + pkg
            if sym not in selected:
                print(f"::warning::DEVICE PACKAGE NOT SELECTED: {pkg} "
                      f"(profile {name})")
                warned += 1
    if warned == 0:
        print("device-package check: no missing packages warned")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 4:
        print("usage: check-device-packages.py <config> <targetinfo> <device>")
        sys.exit(0)
    sys.exit(main(sys.argv[1], sys.argv[2], sys.argv[3]))
